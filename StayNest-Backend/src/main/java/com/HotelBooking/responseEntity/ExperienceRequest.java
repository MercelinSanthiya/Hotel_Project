package com.HotelBooking.responseEntity;

import org.springframework.web.multipart.MultipartFile;

public class ExperienceRequest {

    private String name;
    private String duration;
    private Double price;
    private Integer slotsLeft;
    private String description;
    private String status;
    private MultipartFile image;

    private Integer offerPercent;
    private String offerExpiry;

    public Integer getOfferPercent() {
        return offerPercent;
    }

    public void setOfferPercent(Integer offerPercent) {
        this.offerPercent = offerPercent;
    }

    public String getOfferExpiry() {
        return offerExpiry;
    }

    public void setOfferExpiry(String offerExpiry) {
        this.offerExpiry = offerExpiry;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDuration() {
        return duration;
    }

    public void setDuration(String duration) {
        this.duration = duration;
    }

    public Double getPrice() {
        return price;
    }

    public void setPrice(Double price) {
        this.price = price;
    }

    public Integer getSlotsLeft() {
        return slotsLeft;
    }

    public void setSlotsLeft(Integer slotsLeft) {
        this.slotsLeft = slotsLeft;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public MultipartFile getImage() {
        return image;
    }

    public void setImage(MultipartFile image) {
        this.image = image;
    }
}